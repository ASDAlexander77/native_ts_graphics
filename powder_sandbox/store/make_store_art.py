#!/usr/bin/env python3
"""Draws Powder Sandbox's icon, once, for the APK and for the store:

- powder_sandbox/android/res/: the launcher icon as an adaptive icon (Android 8+): a background,
  a foreground and a monochrome layer (Android 13's themed icons), vector drawables 108 dp across;
- powder_sandbox/store/listing/en-US/images/icon.png: the store's 512 x 512 icon, the same shapes
  rendered (the background's square: the store rounds it);
- .../featureGraphic.png: 1024 x 500, a frame of the game (--frame, a -testOutput PNG) under the
  title.

The shapes are in the adaptive icon's 108-unit square; what matters stays inside its 66-unit safe
circle (a launcher's mask crops the rest). Run again after changing them:

    python powder_sandbox/store/make_store_art.py --frame <showcase.png>
"""
import argparse
import math
import os

from PIL import Image, ImageDraw, ImageFilter, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(os.path.dirname(HERE), "android", "res")
IMAGES = os.path.join(HERE, "listing", "en-US", "images")

BACKGROUND = "#1B2442"
BACKGROUND_GLOW = "#2C3D6E"
SAND = "#E9B44C"
SAND_SHADE = "#C98F2E"
WATER = "#3FA7F5"
EMBER = "#FF6A2B"
MONO = "#FFFFFF"

# The pile: a curve from (26, 84) over (54, 40) to (82, 84) (its peak at (54, 62)), its base along
# y = 84.
PILE = [(26.0, 84.0), (54.0, 40.0), (82.0, 84.0)]
# Its shade: the curve's right half (from the peak).
SHADE = [(54.0, 62.0), (68.0, 62.0), (82.0, 84.0)]
# The stream of grains falling onto the pile's top (x, y, radius).
GRAINS = [(54.0, 31.0, 2.0), (54.4, 38.0, 2.2), (53.7, 45.0, 2.4), (54.2, 52.0, 2.6)]
# A water drop (left) and an ember (right) in flight.
DROP = (36.0, 50.0, 5.0)
EMBER_DOT = (72.0, 46.0, 3.6)


def quad_points(p0, p1, p2, n=48):
    out = []
    for i in range(n + 1):
        t = i / n
        a = (1 - t) * (1 - t)
        b = 2 * (1 - t) * t
        c = t * t
        out.append((a * p0[0] + b * p1[0] + c * p2[0], a * p0[1] + b * p1[1] + c * p2[1]))
    return out


def circle_path(x, y, r):
    return (f"M{x - r:.2f},{y:.2f} a{r:.2f},{r:.2f} 0 1,0 {2 * r:.2f},0 "
            f"a{r:.2f},{r:.2f} 0 1,0 {-2 * r:.2f},0 Z")


def drop_path(x, y, r):
    # a round bottom with a point on top
    return (f"M{x:.2f},{y - 2.2 * r:.2f} C{x + 0.6 * r:.2f},{y - 1.2 * r:.2f} {x + r:.2f},{y - 0.6 * r:.2f} "
            f"{x + r:.2f},{y:.2f} A{r:.2f},{r:.2f} 0 1,1 {x - r:.2f},{y:.2f} "
            f"C{x - r:.2f},{y - 0.6 * r:.2f} {x - 0.6 * r:.2f},{y - 1.2 * r:.2f} {x:.2f},{y - 2.2 * r:.2f} Z")


def drop_points(x, y, r, n=40):
    pts = []
    # the round bottom, from the right side round to the left
    for i in range(n + 1):
        a = math.pi * i / n
        pts.append((x + r * math.cos(a), y + r * math.sin(a)))
    # up to the point and back
    top = (x, y - 2.2 * r)
    left = quad_points((x - r, y), (x - r, y - 1.4 * r), top, 12)
    right = quad_points(top, (x + r, y - 1.4 * r), (x + r, y), 12)
    return pts + left[1:] + right[1:]


def pile_path(points):
    p0, p1, p2 = points
    return f"M{p0[0]:.2f},{p0[1]:.2f} Q{p1[0]:.2f},{p1[1]:.2f} {p2[0]:.2f},{p2[1]:.2f} Z"


def shade_path(points):
    p0, p1, p2 = points
    return (f"M{p0[0]:.2f},{p0[1]:.2f} Q{p1[0]:.2f},{p1[1]:.2f} {p2[0]:.2f},{p2[1]:.2f} "
            f"L{p0[0]:.2f},{p2[1]:.2f} Z")


def vector(paths):
    body = "\n".join(f'    <path android:fillColor="{color}" android:pathData="{data}" />' for color, data in paths)
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- Generated by powder_sandbox/store/make_store_art.py: change it there. -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="108dp" android:height="108dp"\n'
            '    android:viewportWidth="108" android:viewportHeight="108">\n'
            f"{body}\n</vector>\n")


def foreground_paths(mono):
    sand = MONO if mono else SAND
    paths = [(sand, pile_path(PILE))]
    if not mono:
        paths.append((SAND_SHADE, shade_path(SHADE)))
    for x, y, r in GRAINS:
        paths.append((sand, circle_path(x, y, r)))
    paths.append((MONO if mono else WATER, drop_path(*DROP)))
    paths.append((MONO if mono else EMBER, circle_path(*EMBER_DOT)))
    return paths


def write_res():
    drawable = os.path.join(RES, "drawable")
    anydpi = os.path.join(RES, "mipmap-anydpi-v26")
    os.makedirs(drawable, exist_ok=True)
    os.makedirs(anydpi, exist_ok=True)
    background = [(BACKGROUND, "M0,0 H108 V108 H0 Z"), (BACKGROUND_GLOW, circle_path(54.0, 70.0, 40.0))]
    files = {
        os.path.join(drawable, "ic_launcher_background.xml"): vector(background),
        os.path.join(drawable, "ic_launcher_foreground.xml"): vector(foreground_paths(False)),
        os.path.join(drawable, "ic_launcher_monochrome.xml"): vector(foreground_paths(True)),
        os.path.join(anydpi, "ic_launcher.xml"):
            '<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- Generated by powder_sandbox/store/make_store_art.py: change it there. -->\n'
            '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
            '    <background android:drawable="@drawable/ic_launcher_background" />\n'
            '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
            '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n'
            '</adaptive-icon>\n',
    }
    for path, text in files.items():
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)


def render_icon(size):
    """The icon at size pixels: the 108-unit square's middle 72 units (what a launcher's mask
    leaves, roughly), so the store's icon isn't mostly margin."""
    ss = 4
    full = size * ss
    unit = full / 72.0
    offset = 18.0  # units cropped on each side

    def p(x, y):
        return ((x - offset) * unit, (y - offset) * unit)

    image = Image.new("RGBA", (full, full), BACKGROUND)
    draw = ImageDraw.Draw(image)
    cx, cy = p(54.0, 70.0)
    r = 40.0 * unit
    glow = Image.new("RGBA", (full, full), (0, 0, 0, 0))
    ImageDraw.Draw(glow).ellipse((cx - r, cy - r, cx + r, cy + r), fill=BACKGROUND_GLOW)
    image = Image.alpha_composite(image, glow.filter(ImageFilter.GaussianBlur(full / 12)))
    draw = ImageDraw.Draw(image)
    draw.polygon([p(x, y) for x, y in quad_points(*PILE)], fill=SAND)
    shade = quad_points(*SHADE) + [(SHADE[0][0], SHADE[2][1])]
    draw.polygon([p(x, y) for x, y in shade], fill=SAND_SHADE)
    for x, y, rr in GRAINS:
        (px, py), pr = p(x, y), rr * unit
        draw.ellipse((px - pr, py - pr, px + pr, py + pr), fill=SAND)
    draw.polygon([p(x, y) for x, y in drop_points(*DROP)], fill=WATER)
    (px, py), pr = p(EMBER_DOT[0], EMBER_DOT[1]), EMBER_DOT[2] * unit
    draw.ellipse((px - pr, py - pr, px + pr, py + pr), fill=EMBER)
    return image.resize((size, size), Image.LANCZOS)


def feature_graphic(frame_path):
    width, height = 1024, 500
    frame = Image.open(frame_path).convert("RGB")
    # the grid only: not the HUD over it nor the toolbar under it
    frame = frame.crop((0, frame.height * 14 // 100, frame.width, frame.height * 82 // 100))
    # cover the graphic with the frame's middle
    scale = max(width / frame.width, height / frame.height)
    frame = frame.resize((math.ceil(frame.width * scale), math.ceil(frame.height * scale)), Image.LANCZOS)
    left = (frame.width - width) // 2
    top = (frame.height - height) // 2
    image = frame.crop((left, top, left + width, top + height)).convert("RGBA")
    # a dark band on the left for the title
    band = Image.new("RGBA", (width, height), (0, 0, 0, 0))
    band_draw = ImageDraw.Draw(band)
    for x in range(560):
        alpha = int(215 * min(1.0, (560 - x) / 220.0))
        band_draw.line([(x, 0), (x, height)], fill=(14, 19, 38, alpha))
    image = Image.alpha_composite(image, band)
    icon = render_icon(150)
    mask = Image.new("L", (150, 150), 0)
    ImageDraw.Draw(mask).rounded_rectangle((0, 0, 149, 149), radius=34, fill=255)
    image.paste(icon, (56, 92), mask)
    draw = ImageDraw.Draw(image)
    fonts = os.path.join(os.environ.get("WINDIR", "C:/Windows"), "Fonts")
    title = ImageFont.truetype(os.path.join(fonts, "segoeuib.ttf"), 64)
    subtitle = ImageFont.truetype(os.path.join(fonts, "segoeui.ttf"), 30)
    draw.text((56, 262), "Powder Sandbox", font=title, fill="#FFFFFF")
    draw.text((58, 348), "Sand, water, fire and more:", font=subtitle, fill="#C9D3F0")
    draw.text((58, 386), "real physics in your hands", font=subtitle, fill="#C9D3F0")
    return image.convert("RGB")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--frame", help="a frame of the game (PNG) for the feature graphic")
    args = parser.parse_args()
    write_res()
    os.makedirs(IMAGES, exist_ok=True)
    render_icon(512).convert("RGB").save(os.path.join(IMAGES, "icon.png"))
    if args.frame:
        feature_graphic(args.frame).save(os.path.join(IMAGES, "featureGraphic.png"))
    print(f"wrote {RES} and {IMAGES}")


if __name__ == "__main__":
    main()
