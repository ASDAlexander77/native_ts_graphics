// Writes core/nvrhi.editor.<os>.ts, what tsc (and the editor) read for `import { nvrhi } from "../core/nvrhi"`.
//
// tslang merges the `nvrhi` namespaces of core/nvrhi_types.ts, nvrhi_classes.<os>.ts,
// nvrhi_abi.<os>.ts and nvrhi.ts into one; TypeScript keeps one per module, so IDevice, the
// constants and the rest look missing from nvrhi.ts and the examples. This emits each file's
// declarations with tsc and puts them in one file, where the namespace blocks merge.
// tsconfig.json's moduleSuffixes picks core/nvrhi.editor.win32.ts (tsconfig.linux.json: .linux)
// before core/nvrhi.ts, and excludes the four sources. (Not core/nvrhi.<os>.ts: tslang would take
// that for the target's nvrhi.ts, as it takes nvrhi_abi.<os>.ts.) Run it again after changing them:
//   node tools/gen_nvrhi_editor.mjs

import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const tsc = process.platform === "win32" ? "tsc.cmd" : "tsc";

// Named tuples as tslang reads them: desc.isRenderTarget works there, and TypeScript only has
// desc[0]. Each tuple type with labels gets its fields as properties too.
const OPTIONAL = process.env.NVRHI_EDITOR_OPTIONAL === "1";

function splitTop(text) {
    const parts = [];
    let depth = 0, start = 0;
    for (let i = 0; i < text.length; i++) {
        const c = text[i];
        if ("[{(<".includes(c)) depth++;
        else if ("]})".includes(c) || (c === ">" && text[i - 1] !== "=")) depth--;
        else if (c === "," && depth === 0) { parts.push(text.slice(start, i)); start = i + 1; }
    }
    if (text.slice(start).trim()) parts.push(text.slice(start));
    return parts.map(p => p.trim());
}

function matching(text, open) {
    let depth = 0;
    for (let i = open; i < text.length; i++) {
        if (text[i] === "[") depth++;
        else if (text[i] === "]" && --depth === 0) return i;
    }
    return -1;
}

// The type text with its labeled tuples (the whole of it, or inside) given as properties
function withFields(type) {
    const text = type.trim();
    if (!text.startsWith("[") || matching(text, 0) !== text.length - 1) return text;
    const elements = splitTop(text.slice(1, -1)).map(e => /^(\w+)(\??):\s*([\s\S]*)$/.exec(e));
    if (!elements.length || elements.some(e => !e)) return text;
    const inner = elements.map(e => `${e[1]}${e[2]}: ${withFields(e[3])}`);
    const fields = elements.map(e => `${e[1]}${OPTIONAL ? "?" : e[2]}: ${withFields(e[3])};`);
    return `[${inner.join(", ")}] & { ${fields.join(" ")} }`;
}

// Every labeled tuple type in the source (after = : < , | & or an opening parenthesis, so not an
// index signature's brackets)
function namedTuplesAsFields(source) {
    let out = "", at = 0;
    const start = /([=:<,|&(])\s*\[(?=\w+\??:\s)/g;
    for (let m; (m = start.exec(source)); ) {
        const open = m.index + m[0].length - 1;
        const close = matching(source, open);
        if (close < 0) continue;
        out += source.slice(at, open) + withFields(source.slice(open, close + 1));
        at = close + 1;
        start.lastIndex = at;
    }
    return out + source.slice(at);
}

for (const os of ["win32", "linux"]) {
    const sources = ["nvrhi_types", `nvrhi_classes.${os}`, `nvrhi_abi.${os}`, "nvrhi"];
    const work = mkdtempSync(join(tmpdir(), "nvrhi-editor-"));
    try {
        const config = join(work, "tsconfig.json");
        writeFileSync(config, JSON.stringify({
            extends: join(root, "tsconfig.json"),
            compilerOptions: {
                types: [join(root, "types/tslang")],
                incremental: false,
                noEmit: false,
                declaration: true,
                emitDeclarationOnly: true,
                outDir: join(work, "out"),
                rootDir: root,
                moduleSuffixes: [""],
            },
            include: [],
            files: sources.map(s => join(root, "core", `${s}.ts`)),
        }));
        // tsc reports the errors the merge fixes, and still emits
        try { execFileSync(tsc, ["-p", config], { stdio: "ignore", shell: true }); } catch { }

        const bodies = sources.map(s => {
            const text = readFileSync(join(work, "out", "core", `${s}.d.ts`), "utf8");
            return text.split(/\r?\n/)
                .filter(l => !/^import "/.test(l) && !/^\/\/\/ <reference/.test(l) && l !== "export {};")
                .join("\n").trim();
        });
        const header = `// Generated by tools/gen_nvrhi_editor.mjs from core/${sources.join(".ts, core/")}.ts: do not edit.\n` +
            `// The declarations of the files tslang merges into the \`nvrhi\` namespace, in one module for tsc.\n\n` +
            `/// <reference path="donut_interop.d.ts" />\n\n`;
        writeFileSync(join(root, "core", `nvrhi.editor.${os}.ts`), namedTuplesAsFields(header + bodies.join("\n\n") + "\n"));
    } finally {
        rmSync(work, { recursive: true, force: true });
    }
}
